import {randomUUID} from 'node:crypto'
import {and, asc, eq, inArray, isNotNull, isNull, lte, ne, or, sql} from 'drizzle-orm'
import {createError} from 'h3'
import {accountBalanceAdjustments, accountPayments, accountGenerationCharges as charges, organizations, systemPrompt, users, type SystemPrompt} from '../db/schema'
import {getDatabase} from './lib/db'
import type {AuthContext} from './accountSession'
import type {GenerationBilling, GenerationOwner} from './useDB'
import {allocateGenerationBilling, readGenerationAllocation} from './generationBilling'
import {CREDIT_EXHAUSTED_CODE, CREDIT_EXHAUSTED_MESSAGE, formatUsdUnits, parseUsdUnits, USD_SCALE, type AccountBalance} from '../../schemas/account-billing'
import {hasConfirmedGenerationPrice} from '../../schemas/generation-billing'

type Database = ReturnType<typeof getDatabase>
type Transaction = Parameters<Parameters<Database['transaction']>[0]>[0]
type Executor = Database | Transaction
type ChargeRow = Pick<SystemPrompt, 'id' | 'organizationId' | 'userId' | 'status' | 'priceUsd' | 'priceSource' | 'billingState' | 'gatewayGenerationId' | 'usageJson'>
const scope = (actor: GenerationOwner) => and(eq(charges.organizationId, actor.organizationId), eq(charges.userId, actor.userId))

/** Call inside the same transaction that persists a generation transition.
 * The conditional posting is the only place that debits remaining credit. */
export async function recordGenerationCharge(tx: Transaction, row: ChargeRow, options: {release?: boolean; skipDebit?: boolean} = {}) {
    if (!row.organizationId || !row.userId) return
    const actor = {organizationId: row.organizationId, userId: row.userId}
    const units = parseUsdUnits(row.priceUsd)
    const confirmed = row.billingState === 'confirmed' && hasConfirmedGenerationPrice(row) && units !== undefined
    const estimatedUnits = row.priceSource === 'estimate' && units !== undefined ? units.toString() : null
    await tx.insert(charges).values({generationId: row.id, ...actor, estimatedUnits, gatewayGenerationId: row.gatewayGenerationId}).onConflictDoNothing()
    // Different paid jobs and owner balance resets serialize on the account.
    // Credit updates do not modify account keys. Avoid FOR UPDATE: concurrent
    // charge inserts already hold FK KEY SHARE locks on this same account.
    const [user] = await tx.select({id: users.id}).from(users).where(and(eq(users.id, row.userId), eq(users.organizationId, row.organizationId))).for('no key update').limit(1)
    if (!user) throw new Error('Generation charge account is unavailable')
    if (confirmed) {
        const posted = await tx.update(charges).set({state: 'confirmed', confirmedUnits: units.toString(), confirmedAt: sql`CURRENT_TIMESTAMP`,
            estimatedUnits: null, gatewayGenerationId: row.gatewayGenerationId, claimToken: null, claimExpiresAt: null, updatedAt: sql`CURRENT_TIMESTAMP`})
            .where(and(eq(charges.generationId, row.id), scope(actor), ne(charges.state, 'confirmed'))).returning({id: charges.generationId})
        if (posted.length && !options.skipDebit) await tx.update(users).set({creditBalanceUnits: sql`CASE WHEN ${users.creditBalanceUnits} IS NULL THEN NULL ELSE ${users.creditBalanceUnits} - ${units.toString()}::numeric END`, updatedAt: sql`CURRENT_TIMESTAMP`})
            .where(and(eq(users.id, row.userId), eq(users.organizationId, row.organizationId)))
    } else {
        await tx.update(charges).set({state: options.release ? 'released' : 'outstanding', estimatedUnits,
            gatewayGenerationId: row.gatewayGenerationId, updatedAt: sql`CURRENT_TIMESTAMP`})
            .where(and(eq(charges.generationId, row.id), scope(actor), ne(charges.state, 'confirmed')))
    }
}

/** Finite accounts admit a single unresolved batch at a time. Catalog prices
 * are estimates and cannot provide a trustworthy upper-bound reservation. */
export async function assertGenerationCredit(tx: Transaction, actor: GenerationOwner, batchId: string) {
    const [user] = await tx.select({creditBalanceUnits: users.creditBalanceUnits, disabledAt: users.disabledAt}).from(users)
        .where(and(eq(users.id, actor.userId), eq(users.organizationId, actor.organizationId))).for('no key update').limit(1)
    if (!user || user.disabledAt) throw createError({statusCode: 401, statusMessage: 'Unauthorized'})
    if (user.creditBalanceUnits === null) return
    const [existingBatch] = await tx.select({id: systemPrompt.id}).from(systemPrompt)
        .where(and(eq(systemPrompt.organizationId, actor.organizationId), eq(systemPrompt.userId, actor.userId), eq(systemPrompt.batchId, batchId))).limit(1)
    // Provider calls can return extra outputs after an earlier sibling debited
    // the batch. Persist those paid outputs even if the account is overdrawn.
    // Batch IDs are generated by the server, never accepted from the client.
    if (existingBatch) return
    if (BigInt(user.creditBalanceUnits) <= 0n) throw createError({statusCode: 402, statusMessage: CREDIT_EXHAUSTED_MESSAGE, data: {code: CREDIT_EXHAUSTED_CODE}})
    const [outstanding] = await tx.select({id: charges.generationId}).from(charges).innerJoin(systemPrompt, eq(charges.generationId, systemPrompt.id))
        .where(and(scope(actor), eq(charges.state, 'outstanding'), sql`${systemPrompt.billingState} IS NOT NULL`,
            sql`${systemPrompt.batchId} IS DISTINCT FROM ${batchId}`)).limit(1)
    if (outstanding) throw createError({statusCode: 409, statusMessage: 'Wait for your current batch price to be confirmed before starting another batch.'})
}

export type OutstandingChargeClaim = {
    gatewayGenerationId: string
    tokenUUID: string
    expiresAt: string
    rows: Array<{generationId: number; allocation: ReturnType<typeof readGenerationAllocation>}>
}

export function createAccountBilling(db: Database = getDatabase()) {
    async function registerLegacyOutstanding(actor: GenerationOwner, generationId?: number) {
        return db.transaction(async tx => {
            const candidates = await tx.select({gatewayGenerationId: systemPrompt.gatewayGenerationId}).from(systemPrompt)
                .where(and(eq(systemPrompt.organizationId, actor.organizationId), eq(systemPrompt.userId, actor.userId), isNull(systemPrompt.billingState),
                    isNotNull(systemPrompt.gatewayGenerationId), or(ne(systemPrompt.status, 'pending'), isNull(systemPrompt.status)),
                    generationId ? eq(systemPrompt.id, generationId) : sql`NOT (${systemPrompt.priceSource} IS NOT DISTINCT FROM 'gateway' AND ${systemPrompt.priceUsd} IS NOT NULL AND ${systemPrompt.priceUsd} ~ '^(0|[1-9][0-9]{0,11})(\\.[0-9]{1,12})?$' AND COALESCE(${systemPrompt.usageJson}->'gatewayBilling'->>'isByok', 'false') <> 'true')`))
                .orderBy(asc(systemPrompt.id)).limit(64)
            let registered = 0
            for (const gatewayGenerationId of new Set(candidates.map(row => row.gatewayGenerationId).filter((id): id is string => !!id))) {
                if (registered >= 64) break
                await tx.execute(sql`SELECT pg_advisory_xact_lock(hashtextextended(${`billing:${actor.organizationId}:${actor.userId}:${gatewayGenerationId}`}, 0))`)
                const group = await tx.select().from(systemPrompt).where(and(eq(systemPrompt.organizationId, actor.organizationId), eq(systemPrompt.userId, actor.userId),
                    eq(systemPrompt.gatewayGenerationId, gatewayGenerationId))).orderBy(asc(systemPrompt.id)).limit(33).for('update')
                if (!validChargeGroup(group.map(row => ({generationId: row.id, status: row.status, usageJson: row.usageJson})))) continue
                if (group.filter(row => row.billingState === null).length > 64 - registered) continue
                for (const row of group) {
                    if (row.billingState !== null) continue
                    const alreadyConfirmed = hasConfirmedGenerationPrice(row)
                    const [updated] = await tx.update(systemPrompt).set({billingState: alreadyConfirmed ? 'confirmed' : 'awaiting', updatedAt: sql`CURRENT_TIMESTAMP`})
                        .where(and(eq(systemPrompt.id, row.id), eq(systemPrompt.organizationId, actor.organizationId), eq(systemPrompt.userId, actor.userId), isNull(systemPrompt.billingState))).returning()
                    if (!updated) continue
                    await recordGenerationCharge(tx, updated, {skipDebit: alreadyConfirmed})
                    registered++
                }
            }
            return registered
        })
    }
    async function balanceFor(actor: GenerationOwner, executor: Executor = db): Promise<AccountBalance> {
        // Legacy confirmed history is included without creating ledger rows on
        // a GET. Each new generation has a unique ledger entry and is excluded
        // from this fallback, so refreshes can never add its price twice.
        const result = await executor.execute(sql`
            WITH totals AS (
                SELECT state, confirmed_units, estimated_units FROM ${charges}
                WHERE organization_id = ${actor.organizationId}::uuid AND user_id = ${actor.userId}::uuid
                UNION ALL
                SELECT CASE WHEN p."priceSource" = 'gateway'
                            AND (p."billingState" IS NULL OR p."billingState" = 'confirmed')
                            AND COALESCE(p."usageJson"->'gatewayBilling'->>'isByok', 'false') <> 'true'
                            AND p."priceUsd" ~ '^(0|[1-9][0-9]{0,11})(\\.[0-9]{1,12})?$' THEN 'confirmed' ELSE 'outstanding' END,
                       CASE WHEN p."priceSource" = 'gateway'
                            AND (p."billingState" IS NULL OR p."billingState" = 'confirmed')
                            AND COALESCE(p."usageJson"->'gatewayBilling'->>'isByok', 'false') <> 'true'
                            AND p."priceUsd" ~ '^(0|[1-9][0-9]{0,11})(\\.[0-9]{1,12})?$' THEN p."priceUsd"::numeric * ${USD_SCALE.toString()}::numeric END,
                       CASE WHEN p."priceSource" = 'estimate'
                            AND p."priceUsd" ~ '^(0|[1-9][0-9]{0,11})(\\.[0-9]{1,12})?$' THEN p."priceUsd"::numeric * ${USD_SCALE.toString()}::numeric END
                FROM ${systemPrompt} p
                WHERE p."organizationId" = ${actor.organizationId}::uuid AND p."userId" = ${actor.userId}::uuid
                  AND (p."status" IS NULL OR p."status" <> 'failed' OR p."gatewayGenerationId" IS NOT NULL OR p."priceSource" = 'gateway')
                  AND NOT EXISTS (SELECT 1 FROM ${charges} c WHERE c.generation_id = p.id)
            )
            SELECT summary.*, u.credit_balance_units::text AS credit,
                   (SELECT COALESCE(SUM(p.amount_units), 0)::text FROM ${accountPayments} p
                    WHERE p.organization_id = ${actor.organizationId}::uuid AND p.user_id = ${actor.userId}::uuid) AS paid,
                   EXISTS (SELECT 1 FROM ${charges} c JOIN ${systemPrompt} p ON p.id = c.generation_id
                           WHERE c.organization_id = ${actor.organizationId}::uuid AND c.user_id = ${actor.userId}::uuid
                             AND c.state = 'outstanding' AND p."billingState" IS NOT NULL) AS blocked
            FROM (SELECT COALESCE(SUM(confirmed_units) FILTER (WHERE state = 'confirmed'), 0)::text AS confirmed,
                   COALESCE(SUM(estimated_units) FILTER (WHERE state = 'outstanding'), 0)::text AS estimated,
                   COUNT(*) FILTER (WHERE state = 'outstanding')::int AS outstanding,
                   COUNT(*) FILTER (WHERE state = 'outstanding' AND estimated_units IS NULL)::int AS unknown FROM totals) summary
            JOIN ${users} u ON u.id = ${actor.userId}::uuid AND u.organization_id = ${actor.organizationId}::uuid`)
        // Credit and spending use one PostgreSQL statement snapshot, including
        // concurrent settlement or an owner's available-credit adjustment.
        const total = result.rows[0] as {confirmed: string; estimated: string; outstanding: number; unknown: number; credit: string | null; blocked: boolean; paid: string} | undefined
        if (!total) throw createError({statusCode: 404, statusMessage: 'User not found'})
        const confirmedUnits = BigInt(total.confirmed.split('.')[0]!), paidUnits = BigInt(total.paid)
        return {currency: 'USD', confirmedSpendUsd: formatUsdUnits(confirmedUnits), totalPaidUsd: formatUsdUnits(paidUnits),
            unpaidUsd: formatUsdUnits(confirmedUnits > paidUnits ? confirmedUnits - paidUnits : 0n),
            overpaidUsd: formatUsdUnits(paidUnits > confirmedUnits ? paidUnits - confirmedUnits : 0n),
            outstandingEstimateUsd: formatUsdUnits(BigInt(total.estimated.split('.')[0]!)), outstandingCount: total.outstanding,
            outstandingUnknownCount: total.unknown, actualBalanceUsd: total.credit === null ? null : formatUsdUnits(BigInt(total.credit)),
            unlimited: total.credit === null, generationBlockedByOutstanding: total.blocked}
    }

    async function assertOwner(tx: Transaction, actor: AuthContext, userId: string) {
        // Use the same organization lock as role administration so an owner
        // cannot complete a balance change after a concurrent demotion.
        await tx.select({id: organizations.id}).from(organizations).where(eq(organizations.id, actor.organizationId)).for('no key update').limit(1)
        const [owner] = await tx.select({role: users.role, disabledAt: users.disabledAt, authVersion: users.authVersion}).from(users)
            .where(and(eq(users.id, actor.userId), eq(users.organizationId, actor.organizationId))).limit(1)
        if (!owner || owner.role !== 'owner' || owner.disabledAt || owner.authVersion !== actor.authVersion) throw createError({statusCode: 403, statusMessage: 'Organization owner access required'})
        const [target] = await tx.select({creditBalanceUnits: users.creditBalanceUnits}).from(users)
            .where(and(eq(users.id, userId), eq(users.organizationId, actor.organizationId))).for('no key update').limit(1)
        if (!target) throw createError({statusCode: 404, statusMessage: 'User not found'})
        return target
    }

    async function organizationUserBalance(actor: AuthContext, userId: string) {
        return db.transaction(async tx => {await assertOwner(tx, actor, userId); return {userId, balance: await balanceFor({organizationId: actor.organizationId, userId}, tx)}})
    }

    async function setOrganizationUserBalance(actor: AuthContext, userId: string, actualBalanceUsd: string | null) {
        const units = actualBalanceUsd === null ? null : parseUsdUnits(actualBalanceUsd)
        if (units === undefined) throw createError({statusCode: 400, statusMessage: 'Invalid USD balance'})
        return db.transaction(async tx => {
            const target = await assertOwner(tx, actor, userId)
            await tx.update(users).set({creditBalanceUnits: units === null ? null : units.toString(), updatedAt: sql`CURRENT_TIMESTAMP`})
                .where(and(eq(users.id, userId), eq(users.organizationId, actor.organizationId)))
            await tx.insert(accountBalanceAdjustments).values({id: randomUUID(), organizationId: actor.organizationId, userId, adjustedByUserId: actor.userId,
                previousUnits: target.creditBalanceUnits, actualUnits: units === null ? null : units.toString()})
            return {userId, balance: await balanceFor({organizationId: actor.organizationId, userId}, tx)}
        })
    }

    async function claimOutstandingCharges(actor: GenerationOwner, options: {limit?: number; leaseMs?: number; generationId?: number; nowMs?: number} = {}): Promise<OutstandingChargeClaim[]> {
        const now = options.nowMs ?? Date.now(), limit = Math.max(1, Math.min(4, Math.floor(options.limit ?? 4)))
        const expiresAt = new Date(now + Math.max(30_000, Math.min(300_000, options.leaseMs ?? 300_000))).toISOString()
        return db.transaction(async tx => {
            const candidates = await tx.select({generationId: charges.generationId, gatewayGenerationId: charges.gatewayGenerationId}).from(charges)
                .innerJoin(systemPrompt, eq(systemPrompt.id, charges.generationId))
                .where(and(scope(actor), eq(charges.state, 'outstanding'), isNotNull(charges.gatewayGenerationId), lte(charges.nextCheckAt, new Date(now).toISOString()),
                    or(isNull(charges.claimExpiresAt), lte(charges.claimExpiresAt, new Date(now).toISOString())),
                    or(ne(systemPrompt.status, 'pending'), isNull(systemPrompt.status)), options.generationId ? eq(charges.generationId, options.generationId) : undefined))
                .orderBy(asc(charges.nextCheckAt), asc(charges.generationId)).limit(64)
            const claimed: OutstandingChargeClaim[] = []
            for (const gatewayGenerationId of new Set(candidates.map(row => row.gatewayGenerationId).filter((id): id is string => !!id))) {
                if (claimed.length >= limit) break
                await tx.execute(sql`SELECT pg_advisory_xact_lock(hashtextextended(${`billing:${actor.organizationId}:${actor.userId}:${gatewayGenerationId}`}, 0))`)
                const [active] = await tx.select({id: charges.generationId}).from(charges).where(and(scope(actor), eq(charges.gatewayGenerationId, gatewayGenerationId),
                    eq(charges.state, 'outstanding'), sql`${charges.claimExpiresAt} > ${new Date(now).toISOString()}::timestamptz`)).limit(1)
                if (active) continue
                const group = await tx.select({generationId: systemPrompt.id, status: systemPrompt.status, usageJson: systemPrompt.usageJson}).from(charges)
                    .innerJoin(systemPrompt, eq(systemPrompt.id, charges.generationId)).where(and(scope(actor), eq(charges.gatewayGenerationId, gatewayGenerationId))).limit(33)
                // Wait for every allocated output, including failed saves, to
                // reach a durable row before reconciling the provider total.
                if (!validChargeGroup(group)) continue
                const tokenUUID = randomUUID()
                const rows = await tx.update(charges).set({claimToken: tokenUUID, claimExpiresAt: expiresAt, updatedAt: sql`CURRENT_TIMESTAMP`})
                    .where(and(scope(actor), eq(charges.gatewayGenerationId, gatewayGenerationId), eq(charges.state, 'outstanding'),
                        lte(charges.nextCheckAt, new Date(now).toISOString()), inArray(charges.generationId, group.map(row => row.generationId)))).returning({generationId: charges.generationId})
                if (!rows.length) continue
                const generations = await tx.select({generationId: systemPrompt.id, usageJson: systemPrompt.usageJson}).from(systemPrompt)
                    .where(and(inArray(systemPrompt.id, rows.map(row => row.generationId)), eq(systemPrompt.organizationId, actor.organizationId), eq(systemPrompt.userId, actor.userId)))
                claimed.push({gatewayGenerationId, tokenUUID, expiresAt, rows: generations.map(row => ({generationId: row.generationId, allocation: readGenerationAllocation(row.usageJson)}))})
            }
            return claimed
        })
    }

    async function settleClaim(actor: GenerationOwner, claim: OutstandingChargeClaim, billing: GenerationBilling, nowMs = Date.now()) {
        if (!hasConfirmedGenerationPrice(billing) || billing.gatewayGenerationId !== claim.gatewayGenerationId) throw new Error('Unconfirmed Gateway billing cannot settle a charge')
        return db.transaction(async tx => {
            await tx.execute(sql`SELECT pg_advisory_xact_lock(hashtextextended(${`billing:${actor.organizationId}:${actor.userId}:${claim.gatewayGenerationId}`}, 0))`)
            const eligible = await tx.select({generationId: charges.generationId}).from(charges).where(and(scope(actor), eq(charges.claimToken, claim.tokenUUID),
                eq(charges.gatewayGenerationId, claim.gatewayGenerationId), eq(charges.state, 'outstanding'), sql`${charges.claimExpiresAt} > ${new Date(nowMs).toISOString()}::timestamptz`))
            if (!eligible.length) return []
            const rows = await tx.select().from(systemPrompt).where(and(inArray(systemPrompt.id, eligible.map(row => row.generationId)),
                eq(systemPrompt.organizationId, actor.organizationId), eq(systemPrompt.userId, actor.userId))).orderBy(asc(systemPrompt.id)).for('update')
            const stillEligible = await tx.select({generationId: charges.generationId}).from(charges).where(and(scope(actor), eq(charges.claimToken, claim.tokenUUID),
                eq(charges.gatewayGenerationId, claim.gatewayGenerationId), eq(charges.state, 'outstanding'), sql`${charges.claimExpiresAt} > ${new Date(nowMs).toISOString()}::timestamptz`)).for('update')
            const eligibleIds = new Set(stillEligible.map(row => row.generationId))
            if (!eligibleIds.size) return []
            const group = await tx.select({generationId: systemPrompt.id, status: systemPrompt.status, usageJson: systemPrompt.usageJson}).from(charges)
                .innerJoin(systemPrompt, eq(systemPrompt.id, charges.generationId)).where(and(scope(actor), eq(charges.gatewayGenerationId, claim.gatewayGenerationId))).limit(33)
            if (!validChargeGroup(group)) throw new Error('Gateway charge allocation is unavailable')
            const updated: SystemPrompt[] = []
            for (const row of rows) {
                if (!eligibleIds.has(row.id)) continue
                const allocation = readGenerationAllocation(row.usageJson)
                if (rows.length > 1 && !allocation) throw new Error('Gateway charge allocation is unavailable')
                const effective = allocation ? allocateGenerationBilling(billing, allocation.outputIndex, allocation.outputCount) : billing
                const [settled] = await tx.update(systemPrompt).set({billingState: 'confirmed', priceSource: 'gateway', priceUsd: effective.priceUsd,
                    inputTokens: effective.inputTokens ?? row.inputTokens, outputTokens: effective.outputTokens ?? row.outputTokens,
                    totalTokens: effective.totalTokens ?? row.totalTokens, cachedInputTokens: effective.cachedInputTokens ?? row.cachedInputTokens,
                    reasoningTokens: effective.reasoningTokens ?? row.reasoningTokens,
                    usageJson: {...(row.usageJson ?? {}), ...(effective.usageJson ?? {})}, updatedAt: sql`CURRENT_TIMESTAMP`})
                    .where(and(eq(systemPrompt.id, row.id), eq(systemPrompt.organizationId, actor.organizationId), eq(systemPrompt.userId, actor.userId))).returning()
                if (!settled) continue
                await recordGenerationCharge(tx, settled)
                updated.push(settled)
            }
            return updated
        })
    }

    async function releaseClaim(actor: GenerationOwner, claim: OutstandingChargeClaim, nowMs = Date.now()) {
        await db.update(charges).set({claimToken: null, claimExpiresAt: null, checkAttempts: sql`${charges.checkAttempts} + 1`,
            nextCheckAt: sql`${new Date(nowMs).toISOString()}::timestamptz + (LEAST(900, CASE WHEN ${charges.checkAttempts} = 0 THEN 5 WHEN ${charges.checkAttempts} = 1 THEN 15 ELSE 60 * POWER(2, LEAST(4, ${charges.checkAttempts} - 2)) END) * INTERVAL '1 second')`, updatedAt: sql`CURRENT_TIMESTAMP`})
            .where(and(scope(actor), eq(charges.gatewayGenerationId, claim.gatewayGenerationId), eq(charges.claimToken, claim.tokenUUID),
                eq(charges.state, 'outstanding'), sql`${charges.claimExpiresAt} > ${new Date(nowMs).toISOString()}::timestamptz`))
    }
    return {balanceFor, organizationUserBalance, setOrganizationUserBalance, registerLegacyOutstanding, claimOutstandingCharges, settleClaim, releaseClaim}
}

function validChargeGroup(rows: Array<{generationId: number; status: string | null; usageJson: unknown}>) {
    if (!rows.length || rows.length > 32 || rows.some(row => row.status === 'pending')) return false
    const allocations = rows.map(row => readGenerationAllocation(row.usageJson))
    if (rows.length === 1 && !allocations[0]) return true
    if (allocations.some(allocation => !allocation || allocation.outputCount !== rows.length)) return false
    return new Set(allocations.map(allocation => allocation!.outputIndex)).size === rows.length
}
